 vm.runInNewContext(code,{exports,require:(name:string)=>name==='react'?{useRef:()=>({current:canvas}),useLayoutEffect:(f:()=>unknown)=>effect=f}:name==='react/jsx-runtime'?{jsx:()=>null,jsxs:()=>null}:scrollArt,window:win,document:{fonts:{ready:Promise.resolve()}},matchMedia:()=>({matches:false,addEventListener(){},removeEventListener(){}}),requestAnimationFrame:(f:FrameRequestCallback)=>{queue.set(++id,f);return id;},cancelAnimationFrame:(n:number)=>queue.delete(n),ResizeObserver:class{constructor(f:typeof resize){resize=f;}observe(){}disconnect(){}},MutationObserver:class{observe(){}disconnect(){}}});
