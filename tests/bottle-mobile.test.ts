 const path={getTotalLength:()=>100,getPointAtLength:(n:number)=>{samples++;return {x:130+110*Math.sin(n/100*Math.PI*2),y:295+260*Math.cos(n/100*Math.PI*2)};}};
 const svg={style:{} as Record<string,string>,querySelector:()=>path};
 const photo={getBoundingClientRect:()=>({top:600-win.scrollY,height:800})};
 const page={scrollHeight:5000,getBoundingClientRect:()=>({top:-win.scrollY,width:390,height:5000}),querySelectorAll:(s:string)=>s.startsWith('.split-photo')?[photo]:[],addEventListener:(n:string,f:()=>void)=>pageEvents.set(n,f),removeEventListener:(n:string)=>pageEvents.delete(n)};
